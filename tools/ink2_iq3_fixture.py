#!/usr/bin/env python3
"""Regenerate the offline IQ3_XXS oracle and three trained blocks at pinned revisions."""

import argparse
import hashlib
from pathlib import Path
import re
import subprocess

LLAMA_REV = "d92ea9bb126ab957849dd0c0f1f881a64de7dc86"
MODEL_REV = "07fb508609f0652b3f3b2dca32129fa2b8083260"
MODEL_PATH = "Mainline_Support/Inkling-2-Mini-UD-IQ3_XXS.gguf_file"
# Aligned GGUF data start (11979968), then blk.9.ffn_gate_up_exps.weight's tensor offset.
BLOCK_OFFSET = 11979968 + 4707978240


def generate(llama_root, cached_blocks=None):
    def source(path):
        return subprocess.check_output(
            ["git", "-C", str(llama_root), "show", f"{LLAMA_REV}:{path}"], text=True
        )

    common = source("ggml/src/ggml-common.h")
    quants = source("ggml/src/ggml-quants.c")
    license_text = source("LICENSE")
    tables = []
    for dtype, name, count in [
        ("uint8_t", "kmask_iq2xs", 8),
        ("uint8_t", "ksigns_iq2xs", 128),
        ("uint32_t", "iq3xxs_grid", 256),
    ]:
        pattern = rf"GGML_TABLE_BEGIN\({dtype}, {name}, {count}\)\n(.*?)GGML_TABLE_END\(\)"
        match = re.search(pattern, common, re.S)
        if not match:
            raise ValueError(f"Missing pinned table: {name}")
        tables.append(f"inline constexpr {dtype} {name}[{count}] = {{\n{match[1]}}};\n")
    match = re.search(r"void dequantize_row_iq3_xxs\(.*?\n}\n", quants, re.S)
    if not match:
        raise ValueError("Missing pinned decoder")
    decoder = "inline " + match[0]
    url = f"https://huggingface.co/unsloth/Inkling-2-Mini-GGUF/resolve/{MODEL_REV}/{MODEL_PATH}"
    end = BLOCK_OFFSET + 3 * 98 - 1
    blocks = cached_blocks.read_bytes() if cached_blocks else subprocess.check_output([
        "curl", "--fail", "--location", "--silent", "--show-error", "--max-time", "90",
        "--max-filesize", "294", "--range", f"{BLOCK_OFFSET}-{end}", url,
    ], timeout=95)
    if len(blocks) != 3 * 98 or hashlib.sha256(blocks).hexdigest() != "8052d3caaccc5145f5b70b17e33c48d5b4731c3857f265f8fd6bfccc9a95c003":
        raise ValueError("Trained fixture length or SHA256 differs from the pinned range")
    hex_rows = [", ".join(f"0x{v:02x}" for v in blocks[i:i + 14]) for i in range(0, len(blocks), 14)]
    return (
        "// Generated by tools/ink2_iq3_fixture.py. Do not edit.\n"
        f"// llama.cpp: https://github.com/ggml-org/llama.cpp/tree/{LLAMA_REV}\n"
        f"// Trained blocks: {url}\n"
        f"// Tensor blk.9.ffn_gate_up_exps.weight, first 3 blocks; file byte {BLOCK_OFFSET}.\n"
        f"// Block SHA256: {hashlib.sha256(blocks).hexdigest()}\n"
        "/*\n" + license_text + "*/\n#pragma once\n#include <cassert>\n#include <cstdint>\n#include <cstring>\n\n"
        "namespace ink2_iq3_reference {\n"
        "inline constexpr int QK_K = 256;\n"
        "struct block_iq3_xxs { uint16_t d; uint8_t qs[96]; };\n"
        "static_assert(sizeof(block_iq3_xxs) == 98);\n"
        "inline float from_half(uint16_t h) { _Float16 f; std::memcpy(&f, &h, 2); return float(f); }\n"
        "#define GGML_RESTRICT\n#define GGML_FP16_TO_FP32(h) from_half(h)\n"
        + "\n".join(tables) + "\n" + decoder
        + "#undef GGML_FP16_TO_FP32\n#undef GGML_RESTRICT\n"
        + "inline constexpr uint8_t trained_blocks[294] = {\n    " + ",\n    ".join(hex_rows)
        + "\n};\n}  // namespace ink2_iq3_reference\n"
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("llama_root", type=Path, help="Local llama.cpp clone containing the pinned revision")
    parser.add_argument("--blocks", type=Path, help="Reuse the exact 294-byte model range already downloaded")
    args = parser.parse_args()
    output = Path(__file__).resolve().parents[1] / "tests/fixtures/ink2_iq3_reference.h"
    content = generate(args.llama_root, args.blocks)
    if not output.exists() or output.read_text() != content:
        output.write_text(content)
    print(f"IQ3_XXS oracle: {output}")


if __name__ == "__main__":
    main()
