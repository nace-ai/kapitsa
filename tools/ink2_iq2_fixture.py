#!/usr/bin/env python3
"""Regenerate the offline IQ2 oracle from a pinned llama.cpp revision."""

import argparse
from pathlib import Path
import re
import subprocess

LLAMA_REV = "d92ea9bb126ab957849dd0c0f1f881a64de7dc86"


def generate(llama_root):
    def source(path):
        return subprocess.check_output(
            ["git", "-C", str(llama_root), "show", f"{LLAMA_REV}:{path}"], text=True
        )

    common = source("ggml/src/ggml-common.h")
    quants = source("ggml/src/ggml-quants.c")
    license_text = source("LICENSE")
    tables = []
    for dtype, name, count in [
        ("uint8_t", "kmask_iq2xs", 8),
        ("uint8_t", "ksigns_iq2xs", 128),
        ("uint64_t", "iq2xs_grid", 512),
        ("uint64_t", "iq2s_grid", 1024),
    ]:
        match = re.search(rf"GGML_TABLE_BEGIN\({dtype}, {name}, {count}\)\n(.*?)GGML_TABLE_END\(\)", common, re.S)
        if not match:
            raise ValueError(f"Missing pinned table: {name}")
        tables.append(f"inline constexpr {dtype} {name}[{count}] = {{\n{match[1]}}};\n")
    decoders = []
    for name in ["iq2_xs", "iq2_s"]:
        match = re.search(rf"void dequantize_row_{name}\(.*?\n}}\n", quants, re.S)
        if not match:
            raise ValueError(f"Missing pinned decoder: {name}")
        decoders.append("inline " + match[0])
    return (
        "// Generated by tools/ink2_iq2_fixture.py. Do not edit.\n"
        f"// llama.cpp: https://github.com/ggml-org/llama.cpp/tree/{LLAMA_REV}\n"
        "/*\n" + license_text + "*/\n#pragma once\n#include <cassert>\n#include <cstdint>\n#include <cstring>\n\n"
        "namespace ink2_iq2_reference {\n"
        "inline constexpr int QK_K = 256;\n"
        "struct block_iq2_xs { uint16_t d; uint16_t qs[32]; uint8_t scales[8]; };\n"
        "static_assert(sizeof(block_iq2_xs) == 74);\n"
        "struct block_iq2_s { uint16_t d; uint8_t qs[64]; uint8_t qh[8]; uint8_t scales[8]; };\n"
        "static_assert(sizeof(block_iq2_s) == 82);\n"
        "inline float from_half(uint16_t h) { _Float16 f; std::memcpy(&f, &h, 2); return float(f); }\n"
        "#define GGML_RESTRICT\n#define GGML_FP16_TO_FP32(h) from_half(h)\n"
        + "\n".join(tables) + "\n" + "\n".join(decoders)
        + "#undef GGML_FP16_TO_FP32\n#undef GGML_RESTRICT\n"
        "}  // namespace ink2_iq2_reference\n"
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("llama_root", type=Path, help="Local llama.cpp clone containing the pinned revision")
    args = parser.parse_args()
    output = Path(__file__).resolve().parents[1] / "tests/fixtures/ink2_iq2_reference.h"
    content = generate(args.llama_root)
    if not output.exists() or output.read_text() != content:
        output.write_text(content)
    print(f"IQ2 oracle: {output}")


if __name__ == "__main__":
    main()
