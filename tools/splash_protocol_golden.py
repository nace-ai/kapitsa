def _rejection(protocol, name: str, frame: bytes):
    """The issue Splash reports for a rejected frame, from header or payload."""
    parser = protocol.FrameParser()
    step = parser.consume(frame)
    if step.issue is not None:
        return step.issue
    if step.frame is None:
        raise GoldenError(f"{name}: Splash's parser wants more bytes")
    try:
        protocol.decode_frame(step.frame)
    except protocol.ProtocolError as error:
        return error.issue
    raise GoldenError(f"{name}: Splash accepted the frame")


def build_bad_rows(protocol) -> list[tuple[str, bytes, str]]:
    rows = []
    for name, frame, expected_code, expected_request_id in build_bad_specs(protocol):
        issue = _rejection(protocol, name, frame)
        observed = protocol.issue_code_name(issue.code)
        if observed != expected_code:
            raise GoldenError(
                f"{name}: Splash rejected it with {observed}, but the header "
                f"says {expected_code}; the case needs a different frame or a "
                "corrected code column"
            )
        _expect(name, "issue request id", issue.request_id, expected_request_id)
        rows.append((name, frame, observed))
    return rows


def render(client_rows, event_rows, bad_rows) -> str:
    lines = [
        GENERATED_BY,
        "#pragma once",
        "",
        "struct GoldenBytes { const char* name; const char* hex; };",
        "struct GoldenBad { const char* name; const char* hex; const char* code; };",
        "",
        "static const GoldenBytes kGoldenClient[] = {",
    ]
    for name, frame in client_rows:
        lines.append(f'    {{"{name}", "{frame.hex()}"}},')
    lines.append("};")
    lines.append("static const GoldenBytes kGoldenEvents[] = {")
    for name, frame in event_rows:
        lines.append(f'    {{"{name}", "{frame.hex()}"}},')
    lines.append("};")
    lines.append("static const GoldenBad kGoldenBad[] = {")
    for name, frame, code in bad_rows:
        lines.append(f'    {{"{name}", "{frame.hex()}", "{code}"}},')
    lines.append("};")
    return "\n".join(lines) + "\n"


def diff_summary(path: Path, on_disk: bytes, generated: bytes) -> str:
    """A short account of where the committed header stops being current."""
    old = on_disk.decode("utf-8", "replace").splitlines()
    new = generated.decode("utf-8", "replace").splitlines()
    differing = [i for i in range(min(len(old), len(new))) if old[i] != new[i]]
    if not differing:
        if len(old) != len(new):
            return (
                f"{path}: not current: {len(old)} lines on disk, "
                f"{len(new)} generated"
            )
        for offset, (a, b) in enumerate(zip(on_disk, generated)):
            if a != b:
                return f"{path}: not current: bytes differ at offset {offset}"
        return f"{path}: not current"
    index = differing[0]
    old_line, new_line = old[index], new[index]
    column = next(
        (
            i
            for i, (a, b) in enumerate(zip(old_line, new_line))
            if a != b
        ),
        min(len(old_line), len(new_line)),
    )
    context = 24
    window = slice(max(0, column - context), column + context)

    def excerpt(line: str) -> str:
        prefix = "..." if column > context else ""
        suffix = "..." if column + context < len(line) else ""
        return prefix + line[window] + suffix

    return (
        f"{path}: not current: {len(differing)} of {max(len(old), len(new))} "
        f"lines differ\n"
        f"  first difference at line {index + 1}, column {column + 1}:\n"
        f"    on disk:   {excerpt(old_line)!r}\n"
        f"    generated: {excerpt(new_line)!r}"
    )


def resolve_splash(argument: str | None) -> Path:
    if argument:
        return Path(argument).expanduser().resolve()
    from_environment = os.environ.get("SPLASH_ROOT")
    if from_environment:
        return Path(from_environment).expanduser().resolve()
    return (REPO_ROOT.parent / "splash-1.4.0").resolve()


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=(
            "Regenerate tools/splash_protocol_golden.h from Splash 1.4.0's "
            "server/protocol.py."
        )
    )
    parser.add_argument(
        "splash",
        nargs="?",
        help=(
            "path to a Splash 1.4.0 checkout (default: $SPLASH_ROOT, then "
            "../splash-1.4.0 next to this checkout)"
        ),
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="regenerate in memory, compare with the header, write nothing",
    )
    parser.add_argument(
        "--header",
        type=Path,
        default=DEFAULT_HEADER,
        help="header to write or check (default: tools/splash_protocol_golden.h)",
    )
    args = parser.parse_args(argv)
    header = args.header.expanduser().resolve()
    try:
        protocol = load_protocol(resolve_splash(args.splash))
        generated = render(
            build_client_rows(protocol),
            build_event_rows(protocol),
            build_bad_rows(protocol),
        ).encode()
    except GoldenError as error:
        print(f"error: {error}", file=sys.stderr)
        return 2
    except OSError as error:
        print(f"error: {error}", file=sys.stderr)
        return 2

    if args.check:
        try:
            on_disk = header.read_bytes()
        except OSError as error:
            print(f"error: cannot read {header}: {error}", file=sys.stderr)
            return 2
        if on_disk == generated:
            print(f"{header} is current (sha256 {hashlib.sha256(generated).hexdigest()})")
            return 0
        print(diff_summary(header, on_disk, generated), file=sys.stderr)
        return 1

    try:
        header.write_bytes(generated)
    except OSError as error:
        print(f"error: cannot write {header}: {error}", file=sys.stderr)
        return 2
    print(f"wrote {header} (sha256 {hashlib.sha256(generated).hexdigest()})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
