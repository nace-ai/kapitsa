#!/usr/bin/env python3
"""Regenerate tools/splash_protocol_golden.h from Splash 1.4.0's own protocol.py.

Usage:
    python3 tools/splash_protocol_golden.py [<path-to-splash-1.4.0>]
    python3 tools/splash_protocol_golden.py <path-to-splash-1.4.0> --check

<path-to-splash-1.4.0> is a Splash checkout whose server/protocol.py is
imported by path, so every golden byte comes from Splash's code, not a copy.
It defaults to $SPLASH_ROOT, then to ../splash-1.4.0 next to this checkout.

The header holds three tables:

  kGoldenClient  request/cancel/status/release frames. Each ClientMessage is
                 built from Splash's dataclasses, serialized by Splash's
                 serialize_message, and its header re-emitted by Splash's
                 serialize_frame.
  kGoldenEvents  engine-to-client frames. Each payload is assembled from the
                 layouts in protocol.py (_READY, _START, ...) and then must
                 parse with Splash's FrameParser and decode_frame into the
                 fields the row's name promises.
  kGoldenBad     frames Splash's parser must reject. Each row records the
                 issue code Splash actually reported, after checking it is the
                 code the case is meant to exercise.

--check regenerates in memory, compares with the committed header, writes
nothing, and exits 0 when identical or 1 with a short diff summary.
"""

from __future__ import annotations

import argparse
import hashlib
import importlib.util
import json
import os
import struct
import sys
from dataclasses import replace
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
TOOLS_DIR = Path(__file__).resolve().parent
DEFAULT_HEADER = TOOLS_DIR / "splash_protocol_golden.h"
SPLASH_VERSION = "1.4.0"
PROTOCOL_VERSION = 11
GENERATED_BY = (
    "// Generated by tools/splash_protocol_golden.py from Splash 1.4.0's "
    "server/protocol.py. Do not edit."
)


class GoldenError(Exception):
    """A golden row could not be earned from Splash's own code."""


def _expect(name: str, label: str, got: object, want: object) -> None:
    if got != want:
        raise GoldenError(f"{name}: {label} is {got!r}, expected {want!r}")


def load_protocol(splash_root: Path):
    """Import Splash's server/protocol.py by path and pin its version."""
    protocol_path = splash_root / "server" / "protocol.py"
    if not protocol_path.is_file():
        raise GoldenError(
            f"no server/protocol.py under {splash_root}; pass the path to a "
            f"Splash {SPLASH_VERSION} checkout or set $SPLASH_ROOT"
        )
    release_path = splash_root / "release.json"
    if release_path.is_file():
        try:
            release = json.loads(release_path.read_text())
        except (OSError, ValueError) as error:
            raise GoldenError(f"cannot read {release_path}: {error}") from error
        version = release.get("version") if isinstance(release, dict) else None
        if version != SPLASH_VERSION:
            raise GoldenError(
                f"{splash_root} is Splash {version!r}, this generator pins "
                f"{SPLASH_VERSION}"
            )
    # Importing must not leave .pyc files in the Splash checkout.
    sys.dont_write_bytecode = True
    spec = importlib.util.spec_from_file_location(
        "splash_protocol_1_4_0", protocol_path
    )
    if spec is None or spec.loader is None:
        raise GoldenError(f"cannot import {protocol_path}")
    protocol = importlib.util.module_from_spec(spec)
    # dataclasses resolves a class's module through sys.modules.
    sys.modules[spec.name] = protocol
    try:
        spec.loader.exec_module(protocol)
    except BaseException:
        del sys.modules[spec.name]
        raise
    if protocol.PROTOCOL_VERSION != PROTOCOL_VERSION:
        raise GoldenError(
            f"{protocol_path} is protocol version {protocol.PROTOCOL_VERSION}, "
            f"this generator pins {PROTOCOL_VERSION}"
        )
    if protocol.FRAME_HEADER_BYTES != 16 or protocol._HEADER.size != 16:
        raise GoldenError(f"{protocol_path} has an unexpected frame header size")
    return protocol


def _frame(protocol, frame_type, payload: bytes) -> bytes:
    """A whole frame, header included, from Splash's own serializer."""
    return bytes(protocol.serialize_frame(protocol.Frame(frame_type, payload)))


def _raw_frame(protocol, frame_type, payload: bytes) -> bytes:
    """A header packed by protocol.py around a payload its bounds would reject.

    Only the bad-frame table needs this: Splash's serialize_frame refuses an
    unknown frame type or an undersized request frame, and those are exactly
    what the parser must reject.
    """
    return (
        protocol._HEADER.pack(
            protocol._MAGIC,
            protocol.PROTOCOL_VERSION,
            int(frame_type),
            len(payload),
        )
        + payload
    )


def _base_request(protocol):
    """The request tools/splash_protocol_test.cpp calls base_request()."""
    return protocol.RequestFrame(
        request_id=7,
        priority=protocol.RequestPriority.NORMAL,
        absolute_deadline_unix_micros=1_700_000_000_000_000,
        remaining_deadline_micros=30_000_000,
        logical_max_output_tokens=256,
        prompt_tokens=(1, 2, 3, 248045, 5),
        sampling=protocol.SamplingParameters(),
        seed=0,
        constraint=protocol.ConstraintMode.NONE,
        image_spans=(),
        image_pixels=b"",
        score_tokens=(),
        generation_prompt_tokens=0,
        flags=protocol.RequestFlag(0),
        cache_salt=0,
        thinking_budget=None,
    )


def _client_frame(protocol, message, frame_type) -> bytes:
    """Serialize one client message and re-emit its header via serialize_frame.

    serialize_message validates the message's fields; serialize_frame checks
    the frame type and payload bounds. Both are Splash's code, and they must
    agree byte for byte.
    """
    whole = bytes(protocol.serialize_message(message))
    payload = whole[protocol.FRAME_HEADER_BYTES :]
    reframed = _frame(protocol, frame_type, payload)
    if reframed != whole:
        raise GoldenError(
            f"{frame_type.name.lower()}: serialize_message and serialize_frame "
            "disagree"
        )
    return reframed


def _check_request_encoding(protocol, name: str, request, frame: bytes) -> None:
    """Read the request's fixed head and prompt back through protocol.py."""
    payload = frame[protocol.FRAME_HEADER_BYTES :]
    head = protocol._REQUEST.unpack_from(payload, 0)
    _expect(name, "request id", head[0], request.request_id)
    _expect(name, "priority", head[1], int(request.priority))
    _expect(name, "constraint", head[2], int(request.constraint))
    _expect(name, "absolute deadline", head[3], request.absolute_deadline_unix_micros)
    _expect(name, "remaining deadline", head[4], request.remaining_deadline_micros)
    _expect(name, "logical max output", head[5], request.logical_max_output_tokens)
    _expect(name, "prompt count", head[6], len(request.prompt_tokens))
    _expect(name, "image span count", head[7], len(request.image_spans))
    _expect(
        name,
        "sampling block",
        tuple(head[8:15]),
        protocol._sampling_values(request.sampling),
    )
    _expect(name, "seed", head[15], request.seed)
    _expect(name, "score count", head[16], len(request.score_tokens))
    _expect(name, "generation prompt", head[17], request.generation_prompt_tokens)
    _expect(name, "flags", head[18], int(request.flags))
    _expect(name, "cache salt low", head[19], request.cache_salt & 0xFFFFFFFFFFFFFFFF)
    _expect(name, "cache salt high", head[20], request.cache_salt >> 64)
    if request.thinking_budget is None:
        _expect(name, "thinking budget", head[21:24], (0xFFFFFFFF, 0, 0))
    else:
        budget = request.thinking_budget
        _expect(
            name,
            "thinking budget",
            head[21:24],
            (budget.tokens, len(budget.end), budget.also_ends),
        )
        end_offset = protocol._REQUEST.size + 4 * len(request.prompt_tokens)
        end_words = struct.unpack_from(f"<{len(budget.end)}I", payload, end_offset)
        _expect(name, "thinking end", tuple(end_words), tuple(budget.end))
    prompt_bytes = struct.unpack_from(
        f"<{len(request.prompt_tokens)}I", payload, protocol._REQUEST.size
    )
    _expect(name, "prompt tokens", tuple(prompt_bytes), tuple(request.prompt_tokens))


def build_client_rows(protocol) -> list[tuple[str, bytes]]:
    base = _base_request(protocol)
    sampled = replace(
        base,
        request_id=0x1122334455667788,
        priority=protocol.RequestPriority.FOREGROUND,
        logical_max_output_tokens=1 << 20,
        sampling=protocol.SamplingParameters(0.7, 0.95, 40, 0.5, -0.25, 1.1, 0.05),
        seed=0xFFFFFFFFFFFFFFFE,
        generation_prompt_tokens=3,
        flags=(
            protocol.RequestFlag.IGNORE_END_OF_SEQUENCE
            | protocol.RequestFlag.RETURN_PROGRESS
        ),
        cache_salt=(0xAABBCCDD << 64) | 0x0102030405060708,
    )
    thinking = replace(
        base,
        request_id=9,
        generation_prompt_tokens=2,
        thinking_budget=protocol.ThinkingBudget(512, (11, 248046), 248047),
    )
    requests = (
        ("request_greedy", base),
        ("request_sampled", sampled),
        ("request_thinking", thinking),
    )
    rows: list[tuple[str, bytes]] = []
    for name, request in requests:
        frame = _client_frame(protocol, request, protocol.FrameType.REQUEST)
        _check_request_encoding(protocol, name, request, frame)
        rows.append((name, frame))
    rows.append(
        (
            "cancel",
            _client_frame(protocol, protocol.CancelFrame(7), protocol.FrameType.CANCEL),
        )
    )
    rows.append(
        (
            "status_request",
            _client_frame(
                protocol,
                protocol.StatusRequestFrame(0xFEEDFACE),
                protocol.FrameType.STATUS_REQUEST,
            ),
        )
    )
    rows.append(
        (
            "release_request",
            _client_frame(
                protocol,
                protocol.ReleaseRequestFrame(5),
                protocol.FrameType.RELEASE_REQUEST,
            ),
        )
    )
    return rows


