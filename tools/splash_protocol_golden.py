def _parse_event(protocol, name: str, frame: bytes):
    """Parse one whole frame with Splash's incremental parser, then decode it."""
    parser = protocol.FrameParser()
    step = parser.consume(frame)
    if step.issue is not None:
        raise GoldenError(
            f"{name}: Splash's parser rejected the event: "
            f"{protocol.issue_code_name(step.issue.code)}: {step.issue.message}"
        )
    if step.frame is None:
        raise GoldenError(f"{name}: Splash's parser wants more bytes")
    _expect(name, "consumed bytes", step.consumed_bytes, len(frame))
    event = protocol.decode_frame(step.frame)
    if parser.finish() is not None:
        raise GoldenError(f"{name}: Splash's parser ended mid-frame")
    return event


def build_event_rows(protocol) -> list[tuple[str, bytes]]:
    rows = []
    for name, frame_type, payload, event_class, fields in build_event_specs(protocol):
        frame = _frame(protocol, frame_type, payload)
        event = _parse_event(protocol, name, frame)
        if not isinstance(event, event_class):
            raise GoldenError(
                f"{name}: Splash decoded {type(event).__name__}, expected "
                f"{event_class.__name__}"
            )
        for attribute, expected in fields.items():
            _expect(name, attribute, getattr(event, attribute), expected)
        rows.append((name, frame))
    return rows


