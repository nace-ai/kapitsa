#!/usr/bin/env python3
"""Generate leaderboard-data.js from bench/community/results/*.json.

Usage:
    python3 tools/build_leaderboard_data.py

Writes docs/site/leaderboard-data.js with a LEADERBOARD_DATA array that
leaderboard.html picks up on load.
"""

import json
import glob
import os
import sys

def main():
    repo = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    results_dir = os.path.join(repo, "bench", "community", "results")
    out_path = os.path.join(repo, "docs", "site", "leaderboard-data.js")

    files = sorted(glob.glob(os.path.join(results_dir, "*.json")))
    if not files:
        print("No result files found in", results_dir, file=sys.stderr)
        sys.exit(1)

    results = []
    for f in files:
        try:
            with open(f) as fh:
                results.append(json.load(fh))
        except (json.JSONDecodeError, OSError) as e:
            print(f"warning: skipping {f}: {e}", file=sys.stderr)

    js = "// Auto-generated by tools/build_leaderboard_data.py — do not edit\n"
    js += "var LEADERBOARD_DATA = " + json.dumps(results, separators=(",", ":")) + ";\n"

    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    with open(out_path, "w") as fh:
        fh.write(js)

    print(f"Wrote {len(results)} results to {out_path}")

if __name__ == "__main__":
    main()
