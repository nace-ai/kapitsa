#!/usr/bin/env python3
"""Generate leaderboard-data.js from bench/community/results/*.json.

Usage:
    python3 tools/build_leaderboard_data.py

Writes docs/site/leaderboard-data.js with a LEADERBOARD_DATA array that
leaderboard.html picks up on load. Only the fields the page uses are kept.
"""

import json
import glob
import os
import sys

def trim(result):
    """Keep only the fields the leaderboard page reads."""
    prefill = result.get("results", {}).get("prefill", [{}])
    return {
        "time_utc": result.get("time_utc", ""),
        "kapitsa": {"version": result.get("kapitsa", {}).get("version", "")},
        "mac": {
            "chip": result.get("mac", {}).get("chip", ""),
            "memory_gb": result.get("mac", {}).get("memory_gb", 0),
            "name": result.get("mac", {}).get("name", ""),
        },
        "model": {
            "title": result.get("model", {}).get("title", ""),
            "variant": result.get("model", {}).get("variant", ""),
            "decoding": result.get("model", {}).get("decoding", ""),
        },
        "results": {
            "decode": {"median_tps": result.get("results", {}).get("decode", {}).get("median_tps", 0)},
            "prefill": [{"tps": prefill[0].get("tps", 0)}] if prefill else [],
        },
    }

def uncensored_entry(u):
    """A leaderboard entry for one row of uncensored.json."""
    return {
        "time_utc": u["date"] + "T00:00:00Z",
        "kapitsa": {"version": u.get("kapitsa_commit", "")},
        "mac": {"chip": u["mac"]["chip"], "memory_gb": u["mac"]["memory_gb"], "name": u["mac"]["name"]},
        "model": {"title": u["name"], "variant": u["quant"], "decoding": u["decoding"]},
        "results": {"decode": {"median_tps": u["decode_tps"]}, "prefill": [{"tps": u["prefill_tps"]}] if u.get("prefill_tps") else []},
        "uncensored": {"refusals": u["refusals"], "of": u["refusals_of"], "kl": u["kl"],
                       "source": u["source"], "basis": u["refusal_basis"], "kl_basis": u.get("kl_basis", "claimed")},
    }


def build(repo):
    results_dir = os.path.join(repo, "bench", "community", "results")
    files = sorted(glob.glob(os.path.join(results_dir, "*.json")))
    if not files:
        print("No result files found in", results_dir, file=sys.stderr)
        sys.exit(1)

    results = []
    for f in files:
        try:
            with open(f) as fh:
                results.append(trim(json.load(fh)))
        except (json.JSONDecodeError, OSError) as e:
            print(f"warning: skipping {f}: {e}", file=sys.stderr)

    # Uncensored-model rows (bench/community/uncensored.json): not catalog models, so not `kapitsa bench --submit` results;
    # each carries the Mac and the speed it was measured at, plus its refusals and KL against the base model.
    unc_path = os.path.join(repo, "bench", "community", "uncensored.json")
    if os.path.exists(unc_path):
        with open(unc_path) as fh:
            for u in json.load(fh)["rows"]:
                results.append(uncensored_entry(u))

    # One result per line so two result PRs don't always conflict on a single 39 KB line.
    lines = [json.dumps(r, separators=(",", ":")) for r in results]
    js = "// Auto-generated by tools/build_leaderboard_data.py - do not edit\n"
    js += "var LEADERBOARD_DATA = [\n" + ",\n".join(lines) + "\n];\n"
    return js, len(results)


def output_path(repo):
    return os.path.join(repo, "docs", "site", "leaderboard-data.js")


def write(repo):
    """Write docs/site/leaderboard-data.js; returns (path, number of results). tools/community_table.py calls this."""
    js, count = build(repo)
    out_path = output_path(repo)
    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    with open(out_path, "w") as fh:
        fh.write(js)
    return out_path, count


def main():
    import argparse
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true",
                        help="Exit 1 if the committed file differs from a fresh generation")
    args = parser.parse_args()

    repo = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    out_path = output_path(repo)

    if args.check:
        js, count = build(repo)
        try:
            with open(out_path) as fh:
                existing = fh.read()
        except FileNotFoundError:
            print(f"FAIL: {out_path} not found; run without --check to generate it", file=sys.stderr)
            sys.exit(1)
        if existing == js:
            print(f"OK: leaderboard-data.js is up to date ({count} results)")
        else:
            print(f"FAIL: leaderboard-data.js is stale; regenerate with: python3 tools/build_leaderboard_data.py", file=sys.stderr)
            sys.exit(1)
    else:
        out_path, count = write(repo)
        print(f"Wrote {count} results ({os.path.getsize(out_path)} bytes) to {out_path}")

if __name__ == "__main__":
    main()
