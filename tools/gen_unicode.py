#!/usr/bin/env python3
"""Generates the code point ranges of the Unicode categories the pre-tokenizer regexes use:
src/tokenizer/unicode_tables.inc (Qwen: \\p{L}, \\p{M}, \\p{N}) and, with --cased,
src/tokenizer/unicode_tables_cased.inc (Tekken, Nemotron: \\p{Lu}\\p{Lt}, \\p{Ll}, \\p{Lm}\\p{Lo}).
Usage: gen_unicode.py OUT [--cased]. Run with Python 3.12 (Unicode 15.0.0, the version the tables are at)."""
import sys, unicodedata

def ranges(pred):
    out, start = [], None
    for cp in range(0x110000):
        ok = pred(cp)
        if ok and start is None:
            start = cp
        elif not ok and start is not None:
            out.append((start, cp - 1)); start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out

cat = lambda cp: unicodedata.category(chr(cp))
if "--cased" in sys.argv[2:]:
    tables = {
        "kUpperTitle": ranges(lambda c: cat(c) in ("Lu", "Lt")),
        "kLowerCase": ranges(lambda c: cat(c) == "Ll"),
        "kModOther": ranges(lambda c: cat(c) in ("Lm", "Lo")),
    }
else:
    tables = {
        "kLetter": ranges(lambda c: cat(c)[0] == "L"),
        "kMark": ranges(lambda c: cat(c)[0] == "M"),
        "kNumber": ranges(lambda c: cat(c)[0] == "N"),
    }
with open(sys.argv[1], "w") as f:
    f.write(f"// generated by tools/gen_unicode.py (Unicode {unicodedata.unidata_version})\n")
    for name, rs in tables.items():
        f.write(f"static const uint32_t {name}[][2] = {{\n")
        for a, b in rs:
            f.write(f"  {{0x{a:X}, 0x{b:X}}},\n")
        f.write("};\n")
