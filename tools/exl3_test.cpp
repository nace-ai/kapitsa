// The EXL3 reference decoder and the host-side checks of src/model/moe_exl3.h, CPU only (no model, no GPU):
//  - tile 0 of two of Sushi's MCG fixtures (its src/exl3/fixtures, made by its converter: K2.5 at window 12 and K3 at
//    window 16) decodes to the weights exllamav3 decodes for them (the fixtures' `inner`), bit for bit: the bit stream's
//    order, the tail-biting window, the codeword mask, the MCG codebook and the tensor-core placement;
//  - the placement is a bijection of the 256 cells, MCG's value of codeword 0, the rates rate_of admits, shapes_ok's
//    refusals and project's grid guard;
//  - Qwen4Exp::norm_offset, which decides whether a Flash-Next pack's RMSNorm weights are zero-centred.
// tools/exl3_check runs the kernels against this reference on a GPU.
//   exl3_test        (exit status 1 if any check fails)
