int g_fail = 0, g_pass = 0;

void check(bool ok, const std::string& what) {
  ok ? ++g_pass : ++g_fail;
  printf("%s %s\n", ok ? "PASS" : "FAILED", what.c_str());
}

uint16_t f2h(float f) {
  const _Float16 v = _Float16(f);
  uint16_t h;
  memcpy(&h, &v, 2);
  return h;
}

